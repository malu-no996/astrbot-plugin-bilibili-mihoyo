# Enka 备用源的头像（方形）：角色表的 sprite_id 已与 Enka 静态表逐一核对一致。
# 少数 3.3.3 表里 sprite_id 缺失（存的是角色 ID）的条目会 404，前端 img onerror 兜底。
ENKA_ICON = "https://enka.network/ui/zzz/IconRole%02d.png"

# 官方「代理人方头像」CDN 模板 —— **只由角色 id 决定**，不需要接口给：
#   https://act-webstatic.mihoyo.com/game_record/zzzv2/role_square_avatar/role_square_avatar_<id>.png
# 为什么需要它：`avatar/basic`（角色列表）与 `/index`（玩家概览）**不一定**带
# `role_square_url`，它们带的 hollow_icon_path / group_icon_path 是 180×64 的横版横幅
# （空洞 / 编队用的「脸」），塞进方形头像框里就是「用错了图」（角色对、图不对）。
# ✅ 该模板已用本地 data/zzz/assets 里 408 张缓存逐一核对：37 个角色的方头像哈希与
#    `md5(ROLE_SQUARE_TMPL % id)` 完全一致（含 1581 蕾米埃尔 → 297878c29bceeead1725640819f7eb44.png）。
# 拿不到方头像时**不要退回横版横幅** —— 前端 img onerror 有占位兜底，横幅反而是错的图。
ROLE_SQUARE_TMPL = ("https://act-webstatic.mihoyo.com/game_record/zzzv2/"
                    "role_square_avatar/role_square_avatar_%s.png")


def square_avatar(node: dict) -> str:
    """取「代理人方头像」URL：优先接口给的 role_square_url，没给就按角色 id 拼官方地址。

    `node` 可以是官方 avatar/basic、/index、avatar/info 里的任意一条角色数据，
    也可以只传 {"id": ...}。都取不到 → 空串（前端用占位图，不显示裂图）。
    """
    if not isinstance(node, dict):
        return ""
    url = str(node.get("role_square_url") or "").strip()
    if url:
        return url
    cid = str(node.get("id") or node.get("avatar_id") or node.get("role_id") or "").strip()
    return ROLE_SQUARE_TMPL % cid if cid else ""


def element_name(value) -> str:
    try:
        return ELEMENTS.get(int(value), "")
    except (TypeError, ValueError):
        return ""


def profession_name(value) -> str:
    try:
        return PROFESSIONS.get(int(value), "")
    except (TypeError, ValueError):
        return ""


def enka_icon(sprite) -> str:
    try:
        n = int(sprite)
    except (TypeError, ValueError):
        return ""
    return ENKA_ICON % n if n else ""


def lookup(avatar_id) -> tuple:
    """按 ID 取 (中文名, 全名, 稀有度, 元素, 职业, 阵营, sprite_id)；未知返回空元组。"""
    return CHARS.get(str(avatar_id), ())
